let gLn = "getFC10data::";
function getData(data) {
  let trace = 1,
    ln = gLn + `getData()::`;
  if (trace) {
    console.log(ln + `Incoming data=`);
    console.dir(data, { depth: 1 });
  }
  if (!Buffer.isBuffer(data)) {
    throw new Error(ln + "Incoming data should be a Buffer!");
  }
  let res = Buffer.alloc(3);
  res.writeInt16BE(parseInt(data.length / 2), 0); //КількістьРегістрів (2 байти) + КількістьБайтівДаних(1) + Дані
  res.writeInt8(data.length, 2);
  return Buffer.concat([res, data], 3 + data.length);
}

